"""OpenStreetMap road linework.

OSM is the only openly licensed road network with usable coverage of the North
Eastern Region, and it is real data — surveyed and maintained by people, not
generated by us. So records from this module carry ``REAL`` provenance. Two
obligations come with that. The licence is ODbL: any published map or derived
database has to attribute OpenStreetMap contributors, which is a legal
requirement for a government-facing product and not a nicety. And the coverage is
uneven — trunk routes are well mapped, rural link roads in the hills often carry
no surface, width or weight tags at all. Absent tags are represented as ``None``,
never as a guessed value, because a guess here silently becomes a vehicle
restriction decision later.

That is also why this module does not fill in ``free_flow_speed_kmph`` from the
road class. A record labelled ``REAL`` must not contain a number we invented; the
Phase 2 pipeline applies speed defaults itself, where the assumption can be
recorded as ``DERIVED`` alongside the slope and terrain it is based on. Only an
explicit ``maxspeed`` tag becomes a speed here.

Two sources, for two different jobs. :class:`LocalExtractOSMProvider` reads a
prepared regional extract and is what bulk ingestion uses.
:class:`OverpassOSMProvider` answers small ad-hoc queries against the public API
and must not be used for bulk work — it is a shared volunteer service.
"""

